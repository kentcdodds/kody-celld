#!/usr/bin/env node
// Renders wrangler.fleet.jsonc (git-ignored, beside wrangler.jsonc because celld
// requires `main` to live inside the config's directory) from wrangler.jsonc,
// replacing the dev-only `vars` with operator values read from the environment.
// Run it right before `celld deploy wrangler.fleet.jsonc --bucket ...` so real
// tokens and key material never land in the repository.
//
//   KODY_ADMIN_TOKEN=... KODY_MASTER_KEY=... KODY_PUBLIC_URL=https://kody.example.com \
//     npm run fleet:render
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outFile = path.join(root, 'wrangler.fleet.jsonc')

function stripJsonComments(text) {
	return text
		.replace(/\/\*[\s\S]*?\*\//g, '')
		.replace(/^\s*\/\/.*$/gm, '')
		.replace(/,(\s*[}\]])/g, '$1')
}

function required(name, { minLength = 1 } = {}) {
	const value = process.env[name]
	if (!value || value.length < minLength) {
		console.error(`${name} is required${minLength > 1 ? ` (at least ${minLength} characters)` : ''}.`)
		process.exit(1)
	}
	return value
}

const base = JSON.parse(stripJsonComments(await readFile(path.join(root, 'wrangler.jsonc'), 'utf8')))

const adminToken = required('KODY_ADMIN_TOKEN', { minLength: 32 })
const masterKey = required('KODY_MASTER_KEY', { minLength: 32 })
const publicUrl = required('KODY_PUBLIC_URL')
const allowHttp = process.env.KODY_ALLOW_HTTP_PUBLIC_URL === '1'
if (!/^https:\/\//.test(publicUrl) && !(allowHttp && /^http:\/\//.test(publicUrl))) {
	console.error(
		'KODY_PUBLIC_URL must be an https:// URL; terminate TLS in front of celld ' +
			'(or set KODY_ALLOW_HTTP_PUBLIC_URL=1 for a trusted private network).',
	)
	process.exit(1)
}
for (const [name, value] of [
	['KODY_ADMIN_TOKEN', adminToken],
	['KODY_MASTER_KEY', masterKey],
]) {
	if (value === base.vars?.[name]) {
		console.error(`${name} still has the celld-dev placeholder value; generate a real one (see docs/run-fleet.md).`)
		process.exit(1)
	}
}

const rendered = {
	...base,
	vars: {
		KODY_ADMIN_TOKEN: adminToken,
		KODY_MASTER_KEY: masterKey,
		KODY_PUBLIC_URL: publicUrl,
		...(process.env.KODY_ALLOW_INSECURE_SECRET_HOSTS
			? { KODY_ALLOW_INSECURE_SECRET_HOSTS: process.env.KODY_ALLOW_INSECURE_SECRET_HOSTS }
			: {}),
		...(process.env.KODY_MASTER_KEY_PREVIOUS ? { KODY_MASTER_KEY_PREVIOUS: process.env.KODY_MASTER_KEY_PREVIOUS } : {}),
		// Runtime limits and quota defaults (docs/operations.md); unset/empty = built-in default.
		...Object.fromEntries(
			Object.entries(process.env).filter(
				([name, value]) =>
					/^KODY_(EXECUTE|RUN|RESPONSE|AUDIT|MCP|QUOTA|AI|SEARCH|VECTOR|QDRANT|BLOB|BROWSER|WEBHOOK|EMAIL)_/.test(
						name,
					) &&
					value !== undefined &&
					value !== '',
			),
		),
	},
}

await writeFile(
	outFile,
	`// Generated by scripts/render-fleet-config.mjs — contains operator secrets, never commit.\n${JSON.stringify(rendered, null, 2)}\n`,
	{ mode: 0o600 },
)
console.log(`rendered ${path.relative(root, outFile)} (public url: ${publicUrl})`)
